CREATE EXTENSION IF NOT EXISTS btree_gist;
DROP TABLE IF EXISTS bookings, schedules, master_services, services, masters, clients CASCADE;
DROP DOMAIN IF EXISTS booking_status, iso_weekday, service_minutes, price_amount, phone_number CASCADE;

CREATE DOMAIN phone_number AS varchar(12)
  CHECK (VALUE ~ '^\+7[0-9]{10}$');
CREATE DOMAIN price_amount AS numeric(10,2)
  CHECK (VALUE >= 0);
CREATE DOMAIN service_minutes AS integer
  CHECK (VALUE BETWEEN 15 AND 480);
CREATE DOMAIN iso_weekday AS smallint
  CHECK (VALUE BETWEEN 1 AND 7);
CREATE DOMAIN booking_status AS varchar(12)
  CHECK (VALUE IN ('booked', 'completed', 'cancelled'));

CREATE TABLE clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name varchar(120) NOT NULL CHECK (length(btrim(full_name)) > 0),
  phone phone_number NOT NULL UNIQUE,
  telegram_id bigint UNIQUE
);
CREATE TABLE masters (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name varchar(120) NOT NULL UNIQUE CHECK (length(btrim(full_name)) > 0),
  experience_years smallint NOT NULL DEFAULT 0 CHECK (experience_years BETWEEN 0 AND 60),
  is_active boolean NOT NULL DEFAULT TRUE
);
CREATE TABLE services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(120) NOT NULL UNIQUE CHECK (length(btrim(title)) > 0),
  duration_min service_minutes NOT NULL,
  price_rub price_amount NOT NULL,
  is_active boolean NOT NULL DEFAULT TRUE
);
CREATE TABLE master_services (
  master_id bigint NOT NULL REFERENCES masters(id) ON DELETE RESTRICT,
  service_id bigint NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  PRIMARY KEY (master_id, service_id)
);
CREATE TABLE schedules (
  master_id bigint NOT NULL REFERENCES masters(id) ON DELETE RESTRICT,
  weekday iso_weekday NOT NULL,
  starts_at time NOT NULL,
  ends_at time NOT NULL,
  CONSTRAINT schedule_times CHECK (starts_at < ends_at),
  PRIMARY KEY (master_id, weekday)
);
CREATE TABLE bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  master_id bigint NOT NULL,
  service_id bigint NOT NULL,
  visit_date date NOT NULL,
  starts_at time NOT NULL,
  ends_at time NOT NULL,
  duration_at_booking service_minutes NOT NULL,
  price_at_booking price_amount NOT NULL,
  status booking_status NOT NULL DEFAULT 'booked',
  created_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT booking_master_service
    FOREIGN KEY (master_id, service_id)
    REFERENCES master_services(master_id, service_id) ON DELETE RESTRICT,
  CONSTRAINT booking_time_positive CHECK (ends_at > starts_at),
  CONSTRAINT booking_duration_matches CHECK (
    EXTRACT(EPOCH FROM (ends_at - starts_at)) = duration_at_booking * 60
  ),
  CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
    master_id WITH =,
    tsrange(visit_date + starts_at, visit_date + ends_at, '[)') WITH &&
  ) WHERE (status IN ('booked', 'completed'))
);
CREATE INDEX idx_bookings_day ON bookings(visit_date, master_id, status);

-- При вводе/редактировании активной записи проверяется рабочее время.
CREATE OR REPLACE FUNCTION validate_booking_schedule() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IN ('booked', 'completed') AND NOT EXISTS (
    SELECT 1 FROM schedules s
    WHERE s.master_id = NEW.master_id
      AND s.weekday = EXTRACT(ISODOW FROM NEW.visit_date)::smallint
      AND NEW.starts_at >= s.starts_at
      AND NEW.ends_at <= s.ends_at
  ) THEN
    RAISE EXCEPTION 'Запись вне расписания выбранного мастера'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER check_booking_schedule
BEFORE INSERT OR UPDATE ON bookings
FOR EACH ROW EXECUTE FUNCTION validate_booking_schedule();

-- Изменение/удаление расписания не должно сделать активные записи недопустимыми.
CREATE OR REPLACE FUNCTION protect_schedule() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF EXISTS (
      SELECT 1 FROM bookings b
      WHERE b.master_id = OLD.master_id
        AND EXTRACT(ISODOW FROM b.visit_date)::smallint = OLD.weekday
        AND b.status IN ('booked', 'completed')
    ) THEN
      RAISE EXCEPTION 'Нельзя удалить расписание: есть связанные записи'
        USING ERRCODE = '23503';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.master_id IS DISTINCT FROM NEW.master_id
      OR OLD.weekday IS DISTINCT FROM NEW.weekday THEN
    RAISE EXCEPTION 'Изменять мастер/день расписания нельзя: удалите и создайте строку'
      USING ERRCODE = '23514';
  END IF;
  IF EXISTS (
    SELECT 1 FROM bookings b
    WHERE b.master_id = OLD.master_id
      AND EXTRACT(ISODOW FROM b.visit_date)::smallint = OLD.weekday
      AND b.status IN ('booked', 'completed')
      AND (b.starts_at < NEW.starts_at OR b.ends_at > NEW.ends_at)
  ) THEN
    RAISE EXCEPTION 'Новое расписание не включает существующие записи'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER schedule_guard
BEFORE UPDATE OR DELETE ON schedules
FOR EACH ROW EXECUTE FUNCTION protect_schedule();
